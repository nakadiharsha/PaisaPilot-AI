const centralMcpClient = require('./mcpClient');
const IntentEngine = require('./intentEngine');
const geminiProvider = require('./geminiProvider');

class AgentOrchestrator {
  /**
   * Process a natural language financial query through MCP tools
   */
  async processQuery({ message, sessionId = 'session_default' }) {
    if (!message || typeof message !== 'string') {
      throw new Error('Message is required');
    }

    // Ensure MCP client is initialized
    await centralMcpClient.init();
    const availableTools = centralMcpClient.getTools();

    let plan = null;
    let aiProviderUsed = 'Deterministic MCP Intent Engine';

    // 1. Try Gemini first if key is configured
    if (geminiProvider.isAvailable()) {
      try {
        const geminiPlan = await geminiProvider.planWithGemini(message, availableTools);
        if (geminiPlan && geminiPlan.steps && geminiPlan.steps.length > 0) {
          plan = {
            intent: 'GEMINI_AUTONOMOUS_PLAN',
            description: geminiPlan.reasoning || 'Autonomous MCP tool plan generated by Gemini',
            steps: geminiPlan.steps,
            formatter: null
          };
          aiProviderUsed = 'Gemini 2.5 Flash + MCP SDK';
        }
      } catch (err) {
        console.warn('Gemini planning failed, falling back to IntentEngine:', err.message);
      }
    }

    // 2. Fall back to deterministic intent engine if needed
    if (!plan) {
      plan = IntentEngine.planQuery(message);
    }

    console.log(`🧠 [ORCHESTRATOR] User Message: "${message}"`);
    console.log(`📋 [PLAN] Intent: ${plan.intent} (${plan.description}), Steps: ${plan.steps.length}`);

    // 3. Execute MCP tools sequentially through central MCP client
    const executedSteps = [];
    let requiresApproval = false;
    let approvalDetails = null;

    for (const step of plan.steps) {
      console.log(`➡️  Step: Executing MCP tool "${step.tool}"...`);
      const executionResult = await centralMcpClient.executeTool(step.tool, step.args || {}, sessionId);
      executedSteps.push(executionResult);

      // Check if tool indicates human approval needed
      if (executionResult.result && executionResult.result.requires_human_approval) {
        requiresApproval = true;
        approvalDetails = {
          approvalId: executionResult.result.approval_id,
          toolName: step.tool,
          payeeName: executionResult.result.payee_name,
          payeeUpi: executionResult.result.payee_upi,
          amount: executionResult.result.amount,
          formattedAmount: executionResult.result.formatted_amount,
          uri: executionResult.result.upi_intent_uri,
          qrPayload: executionResult.result.qr_code_payload,
          notice: executionResult.result.security_notice
        };
      }
    }

    // 4. Synthesize final response
    let finalOutput = null;

    // If Gemini is available, try conversational synthesis
    if (geminiProvider.isAvailable() && aiProviderUsed.includes('Gemini')) {
      const geminiText = await geminiProvider.synthesizeResponse(message, executedSteps);
      if (geminiText) {
        finalOutput = {
          text: geminiText,
          cardType: plan.intent.toLowerCase(),
          cardData: executedSteps.map(s => s.result)
        };
      }
    }

    // Otherwise or as fallback, use intent engine formatter
    if (!finalOutput && plan.formatter) {
      finalOutput = plan.formatter(executedSteps);
    } else if (!finalOutput) {
      finalOutput = {
        text: `Successfully executed ${executedSteps.length} MCP tools to fulfill your request.`,
        cardType: 'generic_result',
        cardData: executedSteps.map(s => s.result)
      };
    }

    return {
      success: true,
      query: message,
      intent: plan.intent,
      intentDescription: plan.description,
      aiProvider: aiProviderUsed,
      text: finalOutput.text,
      cardType: finalOutput.cardType,
      cardData: finalOutput.cardData,
      requiresApproval,
      approvalDetails,
      executedSteps: executedSteps.map(s => ({
        toolName: s.toolName,
        serverName: s.serverName,
        serverDisplayName: s.serverDisplayName,
        args: s.args,
        durationMs: s.durationMs,
        success: s.success,
        summary: s.result ? (typeof s.result === 'object' ? Object.keys(s.result).slice(0, 4).join(', ') : 'Completed') : 'Failed'
      })),
      timestamp: new Date().toISOString()
    };
  }
}

module.exports = new AgentOrchestrator();
